export function resolveIconName(value) {
  if (!value) return '';
  const key = String(value).trim();
  return LEGACY_EMOJI_ICONS[key] || key;
}

export function icon(name, cls = 'ico') {
  const inner = PATHS[name];
  if (!inner) return '';
  const filled = ['record', 'record-stop', 'live'].includes(name);
  return `<svg class="${cls}" viewBox="0 0 24 24" ${filled ? 'fill="currentColor" stroke="none"' : 'fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round"'} aria-hidden="true">${inner}</svg>`;
}

export function setIcon(el, name) {
  if (typeof el === 'string') el = document.getElementById(el);
  if (el) el.innerHTML = icon(name, el.className || 'ico');
}

export function initNavIcons() {
  document.querySelectorAll('[data-nav-icon]').forEach(el => {
    const name = el.dataset.navIcon;
    if (name) el.insertAdjacentHTML('afterbegin', icon(name, 'ico ico--sm'));
  });
  document.querySelectorAll('[data-icon]').forEach(el => {
    const name = el.dataset.icon;
    if (name) el.innerHTML = icon(name, el.dataset.iconClass || 'ico');
  });
}

export function withIcon(name, text, cls = 'ico ico--sm') {
  return `<span class="ico-inline">${icon(name, cls)}${text}</span>`;
}

